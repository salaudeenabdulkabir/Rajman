export default function AdminSidebar() {
  const pathname = usePathname();

  function isActive(item: (typeof navItems)[0]) {
    if (item.exact) return pathname === item.href;
    return pathname.startsWith(item.href);
  }

  return (
    <aside className="w-64 min-h-screen bg-[#171717] flex flex-col fixed left-0 top-0 bottom-0 z-40 overflow-y-auto">
      {/* Logo */}
      <div className="flex items-center gap-3 px-6 py-5 border-b border-white/10">
        <div className="relative w-8 h-8 rounded-full overflow-hidden">
          <Image src="/brand/rajman-logo.jpg" alt={BRAND.name} fill className="object-cover" sizes="32px" />
        </div>
        <div>
          <p className="text-white text-sm font-semibold leading-none">{BRAND.shortName}</p>
          <p className="text-white/40 text-xs mt-0.5">Admin</p>
        </div>
      </div>

      {/* Navigation */}
      <nav className="flex-1 px-3 py-4" aria-label="Admin navigation">
        <ul className="space-y-0.5" role="list">
          {navItems.map((item) => {
            const active = isActive(item);
            return (
              <li key={item.href}>
                <Link
                  href={item.href}
                  className={`flex items-center gap-3 px-3 py-2.5 rounded-xl text-sm font-medium transition-all duration-150 ${
                    active
                      ? "bg-[#C89B3C] text-white"
                      : "text-white/60 hover:text-white hover:bg-white/8"
                  }`}
                  aria-current={active ? "page" : undefined}
                >
                  <span className={active ? "text-white" : "text-white/50"}>{item.icon}</span>
                  {item.label}
                </Link>
              </li>
            );
          })}
        </ul>
      </nav>

      {/* View Site */}
      <div className="px-3 py-4 border-t border-white/10">
        <Link
          href={ROUTES.home}
          target="_blank"
          rel="noopener noreferrer"
          className="flex items-center gap-2 px-3 py-2.5 rounded-xl text-sm text-white/50 hover:text-white hover:bg-white/8 transition-all duration-150"
        >
          <ExternalLinkIcon />
          View Public Site
        </Link>
      </div>
    </aside>
  );
}

